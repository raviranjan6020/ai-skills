#!/usr/bin/env bash
# Install ai-skills into local agent tools.
#   ./install.sh global [--overlay <dir>]  -> Claude Code, Codex, Kiro user-level config
#   ./install.sh project <dir>             -> drop AGENTS.md / .cursor / .kiro / CLAUDE.md into a repo
# An overlay is your own folder with the same layout (AGENTS.md, rules/, skills/, agents/).
# It is installed on top of this repo, so personal rules stay out of the shared repo.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OVERLAY=""

strip_frontmatter() { awk 'NR==1 && /^---$/ {fm=1; next} fm && /^---$/ {fm=0; next} !fm' "$1"; }

# Base and overlay dirs, in install order (overlay last, so it wins on name clashes).
sources() { echo "$ROOT"; [ -n "$OVERLAY" ] && echo "$OVERLAY"; return 0; }

# AGENTS.md + all rules as one file, for tools with no include/rules mechanism.
bundle() {
  local src f
  for src in $(sources); do
    [ -f "$src/AGENTS.md" ] && { cat "$src/AGENTS.md"; printf '\n\n'; }
    for f in "$src"/rules/*.md; do [ -f "$f" ] && { strip_frontmatter "$f"; printf '\n\n'; }; done
  done
}

link() { # link <target> <linkpath>  (backs up a real file/dir at linkpath)
  local target=$1 path=$2
  if [ -e "$path" ] && [ ! -L "$path" ]; then mv "$path" "$path.bak.$(date +%s)"; echo "backed up $path"; fi
  ln -sfn "$target" "$path"; echo "linked $path -> $target"
}

# Turn <dest> into a real directory holding one link per entry from base and overlay.
# Older installs linked the whole directory into this repo; anything a tool wrote into it
# (untracked files, e.g. Claude's synced skills) is moved out to the new real directory.
link_entries() { # link_entries <name> <dest>
  local name=$1 dest=$2 src entry
  if [ -L "$dest" ]; then
    rm "$dest"; mkdir -p "$dest"
    git -C "$ROOT" ls-files --others --directory -- "$name/" 2>/dev/null | while read -r entry; do
      entry=${entry%/}; mv "$ROOT/$entry" "$dest/"; echo "moved untracked $ROOT/$entry -> $dest/"
    done
  fi
  mkdir -p "$dest"
  # drop links this installer made earlier, so removed entries do not linger
  find "$dest" -maxdepth 1 -type l | while read -r entry; do
    case "$(readlink "$entry")" in "$ROOT"/*|"${OVERLAY:-/nonexistent}"/*) rm "$entry" ;; esac
  done
  for src in $(sources); do
    for entry in "$src/$name"/*; do [ -e "$entry" ] && link "$entry" "$dest/$(basename "$entry")"; done
  done
  return 0
}

claude_md() { # generated ~/.claude/CLAUDE.md importing base and overlay AGENTS.md
  local path=~/.claude/CLAUDE.md
  if [ -e "$path" ] && [ ! -L "$path" ] && ! grep -q 'generated by ai-skills install.sh' "$path"; then
    mv "$path" "$path.bak.$(date +%s)"; echo "backed up $path"
  fi
  rm -f "$path"
  {
    echo "<!-- generated by ai-skills install.sh; edit the sources and re-run it -->"
    sed "s|@~/ai-skills/AGENTS.md|@$ROOT/AGENTS.md|" "$ROOT/claude/CLAUDE.md"
    if [ -n "$OVERLAY" ] && [ -f "$OVERLAY/AGENTS.md" ]; then printf '\n@%s/AGENTS.md\n' "$OVERLAY"; fi
  } > "$path"
  echo "wrote $path"
}

install_global() {
  # --- Claude Code ---
  mkdir -p ~/.claude
  claude_md
  link_entries rules  ~/.claude/rules
  link_entries skills ~/.claude/skills
  link_entries agents ~/.claude/agents
  if [ -f ~/.claude/settings.json ]; then
    cp ~/.claude/settings.json ~/.claude/settings.json.bak
    jq -s '.[0] * .[1]' ~/.claude/settings.json "$ROOT/claude/settings.json" > ~/.claude/settings.json.tmp
    mv ~/.claude/settings.json.tmp ~/.claude/settings.json
    echo "merged claude/settings.json into ~/.claude/settings.json (backup: settings.json.bak)"
  else
    cp "$ROOT/claude/settings.json" ~/.claude/settings.json; echo "wrote ~/.claude/settings.json"
  fi

  # --- Codex (reads ~/.codex/AGENTS.md; skills in ~/.codex/skills/<name>) ---
  if [ -d ~/.codex ]; then
    bundle > ~/.codex/AGENTS.md; echo "wrote ~/.codex/AGENTS.md (generated bundle; edit the sources)"
    link_entries skills ~/.codex/skills
  fi

  # --- Kiro (steering files in ~/.kiro/steering; skills in ~/.kiro/skills/<name>) ---
  if [ -d ~/.kiro ]; then
    link_entries rules ~/.kiro/steering   # first: it clears this installer's old links
    link "$ROOT/AGENTS.md" ~/.kiro/steering/00-agents.md
    if [ -n "$OVERLAY" ] && [ -f "$OVERLAY/AGENTS.md" ]; then
      link "$OVERLAY/AGENTS.md" ~/.kiro/steering/01-overlay-agents.md
    fi
    link_entries skills ~/.kiro/skills
  fi
}

install_project() {
  local dir=$1
  [ -d "$dir" ] || { echo "no such dir: $dir" >&2; exit 1; }
  cd "$dir"
  # AGENTS.md: read natively by Codex, Cursor, and (via @import) Claude Code.
  [ -e AGENTS.md ] || { bundle > AGENTS.md; echo "wrote AGENTS.md"; }
  [ -e CLAUDE.md ] || { printf '@AGENTS.md\n' > CLAUDE.md; echo "wrote CLAUDE.md (imports AGENTS.md)"; }
  mkdir -p .cursor/rules .kiro/steering
  [ -e .cursor/rules/ai-skills.mdc ] || {
    { printf -- '---\ndescription: ai-skills agent rules\nalwaysApply: true\n---\n'; bundle; } > .cursor/rules/ai-skills.mdc
    echo "wrote .cursor/rules/ai-skills.mdc"; }
  [ -e .kiro/steering/00-agents.md ] || { cp "$ROOT/AGENTS.md" .kiro/steering/00-agents.md; echo "wrote .kiro/steering/00-agents.md"; }
  echo "note: if this is someone else's repo, keep these files local (add to .git/info/exclude)."
}

case "${1:-}" in
  global)
    if [ "${2:-}" = "--overlay" ]; then
      [ -d "${3:-}" ] || { echo "overlay dir not found: ${3:-}" >&2; exit 1; }
      OVERLAY="$(cd "$3" && pwd)"
    fi
    install_global ;;
  project) install_project "${2:?usage: install.sh project <dir>}" ;;
  *) sed -n '2,6p' "$0"; exit 1 ;;
esac
